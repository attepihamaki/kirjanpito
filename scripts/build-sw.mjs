/*
 * Writes the service worker into the static export (CLAUDE.md §11b).
 *
 * Runs on `postbuild`, after `next build` has filled out/ and before
 * verify-export.mjs checks it. The worker needs the list of files the export
 * holds, which only exists once the build is done, so it cannot live in
 * public/.
 *
 * out/sw.js is the two functions in scripts/sw/ printed with `toString()`,
 * plus the list of files to keep for offline use and a version that changes
 * whenever any of them does.
 */

import { createHash } from "node:crypto"
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative, sep } from "node:path"

import { strategyFor } from "./sw/strategy.mjs"
import { worker } from "./sw/worker.mjs"

const OUT = "out"
const TARGET = join(OUT, "sw.js")

/**
 * Files of the export the app never asks for offline: the worker itself, what
 * only crawlers and link previews read, the 404 and the host's own files.
 */
const SKIP = [
  /^sw\.js$/,
  /^robots\.txt$/,
  /^sitemap\.xml$/,
  /^og\//,
  /^404(\.html$|\/)/,
  /^_not-found\//,
  /^CNAME$/,
  /(^|\/)\.[^/]+$/,
]

function walk(dir) {
  const found = []
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry)
    if (statSync(path).isDirectory()) found.push(...walk(path))
    else found.push(path)
  }
  return found
}

if (!existsSync(OUT)) {
  console.error(`✗ ${OUT}/ does not exist. Run \`next build\` first.`)
  process.exit(1)
}

const hash = createHash("sha256")
const precache = []

for (const file of walk(OUT).sort()) {
  const path = relative(OUT, file).split(sep).join("/")
  if (SKIP.some((re) => re.test(path))) continue
  hash.update(path).update("\0").update(readFileSync(file)).update("\0")
  /*
   * A document is requested by its directory, so that is the URL it is kept
   * under. The root's is the empty path, which resolves to the scope itself.
   */
  precache.push(path.replace(/(^|\/)index\.html$/, "$1"))
}

/*
 * The worker's own source is part of the version, so a change to its logic
 * alone still replaces the cache.
 */
const source = `const strategyFor = ${strategyFor.toString()}\n\n;(${worker.toString()})`
const version = hash.update(source).digest("hex").slice(0, 16)

// BUILD stays on one line: verify-export.mjs reads the list back from it.
writeFileSync(
  TARGET,
  `/* Generated by scripts/build-sw.mjs. */\n` +
    `const BUILD = ${JSON.stringify({ version, precache })}\n` +
    `${source}(self, BUILD, strategyFor)\n`
)

console.log(`sw.js written: ${precache.length} files, version ${version}`)
